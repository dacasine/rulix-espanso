#!/usr/bin/env ruby
# frozen_string_literal: true

require 'yaml'
require 'json'
require 'pathname'

root = Pathname.new(__dir__).parent
match_dir = root.join('espanso/match')
helper = 'ruby "$HOME/Library/Application Support/espanso/scripts/legal_link.rb" '

def url_from_match(match)
  text = match['markdown'] || match['replace'] || match['form'] || ''
  url = text.scan(/\]\((https:\/\/[^\s)]+)\)/).last&.first
  return url if url
  rs = text[/\bRS(?:\/[A-Z]+)?\s+([\d.]+)/, 1]
  return unless rs
  trigger = match['trigger'].strip
  return "https://lex.vs.ch/app/fr/texts_of_law/#{rs}" if trigger.start_with?('rsvs')
  return "https://prestations.vd.ch/pub/blv-publication/actes/consolide/#{rs}" if trigger.start_with?('rsvd')
  # Reuse canonical Fedlex URLs where the local engine provides them.
  engine = Pathname.new(__dir__).parent.join('espanso/scripts/fedlex_refs.rb')
  if engine.exist?
    key = trigger.delete_prefix('rs')
    data = engine.read.split("__END__\n", 2).last
    row = data.lines.map { |line| line.chomp.split('|', 5) }.find { |fields| fields[0] == key || fields[2] == rs }
    return row[4] if row && row[4] && !row[4].empty?
  end
  "https://www.fedlex.admin.ch/fr/cc/internal-law/#{rs}"
end

Dir[match_dir.join('*.yml')].sort.each do |file|
  next if file.end_with?('-links.yml')
  # Keep existing comments, ordering and multiline forms intact.
  text = File.read(file)
  blocks = text.split(/(?=^  - (?:trigger|regex|form|triggers):)/)
  blocks.map! do |block|
    next block unless block.start_with?('  - ')
    parsed = YAML.safe_load("matches:\n" + block, aliases: true)['matches'].first
    if parsed['trigger']
      trigger = parsed['trigger']
      trigger += ' ' unless trigger.end_with?(' ')
      block = block.sub(/^(\s*(?:- )?trigger:) .*$/) { "#{$1} #{JSON.generate(trigger)}" }
      if trigger.lstrip.match?(/\A[[:alnum:]]/)
        if parsed.key?('left_word')
          block = block.sub(/^    left_word: .*$/, '    left_word: true')
        else
          block = block.sub(/^(\s*(?:- )?trigger:.*)$/, "\\1\n    left_word: true")
        end
      end
      unless parsed['trigger'].end_with?(' ')
        %w[form replace markdown].each do |field|
          value = parsed[field]
          next unless value.is_a?(String) && !value.match?(/\s\z/)
          # A consumed delimiter remains available after ordinary expansions.
          block = block.sub(/^(\s*(?:- )?#{field}:) [^|>].*$/) { "#{$1} #{JSON.generate(value + ' ')}" }
        end
      end
    elsif parsed['regex']
      regex = parsed['regex'].sub(/\\s\z/, ' ')
      regex += ' ' unless regex.end_with?(' ')
      if regex.match?(/fedlex_law|rulix_law/) && !regex.start_with?('\\b')
        regex = '\\b' + regex
      end
      block = block.sub(/^  - regex: .*$/) { "  - regex: #{JSON.generate(regex)}" }
      if parsed.key?('left_word')
        block = block.sub(/^    left_word: .*$/, '    left_word: true')
      else
        block = block.sub(/^(  - regex:.*)$/, "\\1\n    left_word: true")
      end
      unless parsed['regex'].end_with?(' ', '\\s')
        %w[replace markdown].each do |field|
          value = parsed[field]
          next unless value && !value.match?(/\s\z/)
          block = block.sub(/^(    #{field}:) .*$/) { "#{$1} #{JSON.generate(value + ' ')}" }
        end
      end
    end
    block
  end
  updated = blocks.join
  File.write(file, updated) if updated != text

  next if File.basename(file).start_with?('_')
  matches = YAML.safe_load(updated, aliases: true)['matches'] || []
  links = matches.map do |match|
    if match['trigger'] && match['trigger'].match?(/\A(?:rs|sr)[a-z0-9]+ /)
      link = { 'trigger' => 'l' + match['trigger'], 'left_word' => true }
      if (url = url_from_match(match))
        link['replace'] = url + "\n"
      elsif match['vars']
        link['replace'] = "{{rulix_link_url}}\n"
        link['vars'] = Marshal.load(Marshal.dump(match['vars']))
        shell = link['vars'].find { |var| var['type'] == 'shell' }
        next unless shell
        shell['name'] = 'rulix_link_url'
        shell['params']['cmd'] = helper + shell['params']['cmd'].gsub('\\"', '"')
      else
        next
      end
      link
    elsif match['regex'] && match['regex'].match?(/fedlex_law|rulix_law/) && match['vars']
      link = { 'regex' => '\\bl' + match['regex'].delete_prefix('\\b'), 'left_word' => true,
               'replace' => "{{rulix_link_url}}\n",
               'vars' => Marshal.load(Marshal.dump(match['vars'])) }
      shell = link['vars'].find { |var| var['type'] == 'shell' }
      next unless shell
      shell['name'] = 'rulix_link_url'
      shell['params']['cmd'] = helper + shell['params']['cmd'].gsub('\\"', '"')
      link
    end
  end
  links.compact!
  next if links.empty?
  dest = file.sub(/\.yml\z/, '-links.yml')
  File.write(dest, "# Generated by scripts/prepare_link_shortcuts.rb\n" + YAML.dump('matches' => links))
  puts "#{File.basename(dest)}: #{links.length} link shortcuts"
end
